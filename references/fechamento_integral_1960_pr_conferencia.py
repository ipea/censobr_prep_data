def main():
    OUT.mkdir(parents=True, exist_ok=True)
    snapshot = json.loads((ROOT / "references/fechamento_integral_1960_evidencias/guia_municipal_anterior.json").read_text(encoding="utf-8"))
    guide = {int(r["cod60"]): r for r in snapshot["linhas"] if "Paran" in r["nome_uf60"]}
    fields = ["pop_total", "pop_urbana", "pop_rural"]
    records = []
    for line in VISUAL.strip().splitlines():
        page, code, *values = map(int, line.split())
        assert code in guide, code
        assert values[0] == values[1] + values[2], (code,values)
        old = {name: int(guide[code][name]) for name in fields}
        new = dict(zip(fields,values))
        records.append({"cod60":code,"nome":guide[code]["nome"],"pagina_pdf":page,"pagina_impressa":page-4,
                        "fonte_imagem":f"quadroII_pdf{page:02d}.png", "guia":old,"sinopse_visual":new,
                        "fonte_pop_anterior":guide[code]["fonte_pop"],
                        "diferencas":{name:new[name]-old[name] for name in fields if new[name]!=old[name]}})
    assert len(records)==len({r["cod60"] for r in records})
    result={"cobertura":len(records),"esperados":len(guide),"faltam":sorted(set(guide)-{r["cod60"] for r in records}),
            "guia_sha256":snapshot["sha256"],
            "totais_guia":{name:sum(int(r[name]) for r in guide.values()) for name in fields},
            "totais_transcritos":{name:sum(r["sinopse_visual"][name] for r in records) for name in fields},
            "linha_estado":dict(zip(fields,[4277763,1327982,2949781])),
            "divergencias":[r for r in records if r["diferencas"]],"municipios":records}
    assert result["cobertura"] == 162 and not result["faltam"]
    assert result["totais_transcritos"] == result["linha_estado"]
    zones = [("Litoral",7100,7104,77253,44793,32460),
             ("Alto Ribeira",7110,7112,56079,6196,49883),
             ("Campos do Oeste",7120,7122,124350,23188,101162),
             ("Castro",7130,7131,44198,14440,29758),
             ("Campos Gerais",7140,7148,228801,107485,121316),
             ("Curitiba",7150,7159,520535,391587,128948),
             ("Tomazina",7170,7183,189041,38522,150519),
             ("Alto Ivai",7190,7195,114715,15403,99312),
             ("Irati",7200,7209,152058,47054,105004),
             ("Oeste",7220,7268,1556815,298486,1258329),
             ("Norte",7300,7350,1213918,340828,873090)]
    result["zonas_conferidas"] = []
    for name,lo,hi,*expected in zones:
        members=[r for r in records if lo<=r["cod60"]<=hi]
        observed=[sum(r["sinopse_visual"][f] for r in members) for f in fields]
        assert observed==expected,(name,observed,expected)
        result["zonas_conferidas"].append({"zona":name,"n_municipios":len(members),"soma_municipal":dict(zip(fields,observed)),"linha_zona":dict(zip(fields,expected))})
    (OUT/"conferencia_162_municipios.json").write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding="utf-8")
    print(json.dumps({k:v for k,v in result.items() if k!="municipios"},ensure_ascii=False,indent=2))


if __name__ == "__main__":
    main()
